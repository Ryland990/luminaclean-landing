#!/usr/bin/env python3
"""Rebuild content/POST-TRACKER.md from content/tracker/weekly.csv + posts.csv.

weekly.csv: one row per (Mon–Sun week, page). Columns:
  gsc_impr/gsc_clicks/gsc_pos  — GSC Performance, breakdown=page, that week
  longq_impr/longq_clicks       — same page, query regex ^(\\S+\\s){6,}\\S+$ (7+ word questions)
  fk_views/fk_taps              — FolioKit web_weekly('luminacleanweb','luminaclean') views / App Store taps
posts.csv: page, changed (YYYY-MM-DD), type (answer | new | outrank-new), note.

Usage: python3 content/tracker/build.py --through 2026-10-28   (last day GSC has data for)
"""
import argparse, csv, datetime as dt, os, re, html, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SHOW_WEEKS = 6

ap = argparse.ArgumentParser()
ap.add_argument('--through', required=True, help='last date with GSC data, YYYY-MM-DD')
through = dt.date.fromisoformat(ap.parse_args().through)

data = collections.defaultdict(dict)
weeks = set()
for r in csv.DictReader(open(os.path.join(HERE, 'weekly.csv'))):
    data[r['page']][r['week']] = r
    weeks.add(r['week'])
weeks = sorted(weeks)[-SHOW_WEEKS:]
partial = {w for w in weeks if dt.date.fromisoformat(w) + dt.timedelta(days=6) > through}
full = [w for w in weeks if w not in partial]


def n(page, week, col):
    v = data[page].get(week, {}).get(col, '')
    return int(float(v)) if v not in ('', None) else 0


def question(page):
    try:
        t = open(os.path.join(ROOT, page + '.html'), encoding='utf-8').read()
    except FileNotFoundError:
        return ''
    for attrs, txt in re.findall(r'<h2([^>]*)>(.*?)</h2>', t, re.S):
        q = html.unescape(re.sub('<[^>]+>', '', txt)).strip()
        if 'id=' in attrs and q.endswith(('?', '？')):
            return q
    return ''


def verdict(page, changed, typ):
    after = [w for w in full if w >= week_of(changed)]
    before = [w for w in full if w < week_of(changed)][-3:]
    imp_after = [n(page, w, 'gsc_impr') for w in after]
    lq_after = [n(page, w, 'longq_impr') for w in after]
    if len(after) < 2:
        return 'Too early (<2 full weeks)'
    if sum(imp_after) == 0:
        return 'No impressions yet — check indexing in GSC'
    if typ in ('new', 'outrank-new') or not before:
        return f'Showing up ({imp_after[-1]} impr last full wk)'
    base = sum(n(page, w, 'longq_impr') for w in before) / len(before)
    now = sum(lq_after[-2:]) / len(lq_after[-2:])
    if base == 0:
        return 'Up (new questions)' if now > 0 else 'Flat (no long questions)'
    ch = (now - base) / base
    return ('Up' if ch >= .2 else 'Down' if ch <= -.2 else 'Flat') + f' ({ch:+.0%} long-question impr)'


def week_of(d):
    d = dt.date.fromisoformat(d)
    return (d - dt.timedelta(days=d.weekday())).isoformat()


def series(page, col):
    cell = lambda w: str(n(page, w, col)) if data[page].get(w, {}).get(col, '') != '' or col.startswith('gsc') else '–'
    return ' · '.join(cell(w) + ('*' if w in partial else '') for w in weeks)


posts = list(csv.DictReader(open(os.path.join(HERE, 'posts.csv'))))
lab = ' · '.join(dt.date.fromisoformat(w).strftime('%b %-d') + ('*' if w in partial else '') for w in weeks)

out = [
    '# Post tracker — luminaclean.app',
    '',
    f'Generated by `content/tracker/build.py` · GSC data through {through} · weeks Mon–Sun · `*` = partial week.',
    'Read it as: did the post start showing for its questions (long-question impressions), then clicks, then FolioKit views/App Store taps.',
    'Verdict compares the last 2 full weeks after the change with the 3 full weeks before it. Google needs 2–4 weeks, so judge at week 4.',
    '',
    f'Week columns: {lab}',
    '',
]
cohorts = collections.OrderedDict()
for p in sorted(posts, key=lambda p: (p['changed'], p['page']), reverse=True):
    cohorts.setdefault((p['changed'], p['type']), []).append(p)
names = {'answer': 'answer heading added', 'new': 'new posts', 'outrank-new': 'Outrank posts published'}
for (changed, typ), ps in cohorts.items():
    out += [f'## {changed} — {names[typ]} ({len(ps)})', '',
            '| Post | Question on the page | Long-question impr / wk | All impr / wk | Clicks / wk | FolioKit views · taps (last full wk) | Verdict |',
            '|---|---|---|---|---|---|---|']
    for p in sorted(ps, key=lambda p: -sum(n(p['page'], w, 'gsc_impr') for w in weeks)):
        pg = p['page']
        lw = full[-1] if full else weeks[-1]
        out.append(f"| [{pg.split('/')[-1]}](https://luminaclean.app/{pg}.html) | {question(pg) or '—'} | {series(pg, 'longq_impr')} | "
                   f"{series(pg, 'gsc_impr')} | {series(pg, 'gsc_clicks')} | {n(pg, lw, 'fk_views')} · {n(pg, lw, 'fk_taps')} | "
                   f"{verdict(pg, changed, typ)}{' — ' + p['note'] if p['note'] else ''} |")
    out.append('')
open(os.path.join(ROOT, 'content', 'POST-TRACKER.md'), 'w').write('\n'.join(out))
print('wrote content/POST-TRACKER.md:', len(posts), 'posts,', len(weeks), 'weeks')
